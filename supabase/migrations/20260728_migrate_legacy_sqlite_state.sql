-- Importul din SQLite pastreaza ID-urile vechi pentru a conserva relatiile.
-- Dupa import, secventele identity trebuie mutate dupa cel mai mare ID copiat.
create or replace function public.sync_legacy_identity_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    target_sequence text;
    maximum_id bigint;
begin
    foreach target_sequence in array array[
        'learning_progress',
        'tracked_students',
        'activity_link_activations',
        'activity_test_sessions',
        'activity_events'
    ]
    loop
        execute format('select coalesce(max(id), 0) from public.%I', target_sequence)
            into maximum_id;
        if maximum_id = 0 then
            perform setval(
                pg_get_serial_sequence('public.' || target_sequence, 'id'),
                1,
                false
            );
        else
            perform setval(
                pg_get_serial_sequence('public.' || target_sequence, 'id'),
                maximum_id,
                true
            );
        end if;
    end loop;
end;
$$;

revoke all on function public.sync_legacy_identity_sequences() from public;
grant execute on function public.sync_legacy_identity_sequences() to service_role;
