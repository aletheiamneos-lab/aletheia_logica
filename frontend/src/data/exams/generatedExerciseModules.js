function usesPartBasedZipSchema(studentExam) {
  const sections = studentExam?.sections ?? []
  const hasPartCollections = sections.some((section) => Array.isArray(section.parts))
  const hasModernSectionIds = sections.some((section) => {
    const id = String(section?.id ?? "")
    return ["I", "II", "III", "I_A", "I_B"].includes(id) || /^[IVX]+_[A-Z]$/i.test(id)
  })
  const hasCompact2018Shape = Boolean(
    studentExam?.examMeta ??
      studentExam?.metadata ??
      studentExam?.sourcePolicy ??
      studentExam?.sourceFiles ??
      (hasOwn(studentExam, "totalPoints") && hasOwn(studentExam, "officialPoints")),
  )

  return Boolean(hasPartCollections || hasModernSectionIds || hasCompact2018Shape)
}

function normalizeZipPartKey(value) {
  return String(value ?? "")
    .replace(/[._-]/g, "")
    .toUpperCase()
}

function normalizePartAnswerValue(value, caseMode = "preserve") {
  if (Array.isArray(value)) {
    return value.map((entry) => normalizePartAnswerValue(entry, caseMode)).filter(Boolean)
  }

  if (value && typeof value === "object") {
    const scalar = value.variant ?? value.letter ?? value.value ?? value.answer ?? value.correctAnswer ?? value.correctLetter
    return scalar === undefined ? "" : normalizePartAnswerValue(scalar, caseMode)
  }

  const text = String(value ?? "").trim()
  if (caseMode === "lower") {
    return text.toLowerCase()
  }
  if (caseMode === "upper") {
    return text.toUpperCase()
  }
  return text
}

function isPartAutomaticAnswerValue(value) {
  const normalized = normalizePartAnswerValue(value)
  if (Array.isArray(normalized)) {
    return normalized.length > 0 && normalized.every((entry) => /^[A-Za-z]$/.test(String(entry)))
  }

  return /^[A-Za-z]$/.test(String(normalized))
}

function isPartAutomaticAnswerMap(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return false
  }

  const entries = Object.entries(value)
  const wrapperKeys = new Set(["variant", "letter", "value", "answer", "correctAnswer", "correctLetter"])

  return (
    entries.length > 0 &&
    !entries.every(([key]) => wrapperKeys.has(String(key))) &&
    entries.every(([key, answer]) => String(key ?? "").trim() && isPartAutomaticAnswerValue(answer))
  )
}

function normalizePartValidity(value) {
  const text = stripZipDiacritics(value).toLowerCase()
  if (text.includes("nevalid") || text.includes("invalid")) {
    return "invalid"
  }
  if (text.includes("valid")) {
    return "valid"
  }
  return String(value ?? "")
}

