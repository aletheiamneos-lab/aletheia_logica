        id,
        title: `${card.reference ?? id}. ${cleanGeneratedTitle(card.title ?? section.title, card.prompt ?? "Cerinta")}`,
        points,
        officialPrompt: card.prompt,
        items: [generatedCardToBacItem(card, moduleData)],
