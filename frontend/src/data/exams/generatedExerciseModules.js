function buildModuleMap(payload) {
  return Object.fromEntries(
    (payload.modules ?? []).map((moduleData) => {
      const zipDerivedConfig = ZIP_DERIVED_BAC_MODULES[moduleData.slug]

      if (zipDerivedConfig) {
        return [moduleData.slug, buildZipDerivedBacModule(moduleData, zipDerivedConfig)]
      }

      if (moduleData.slug === "exercitiu-bac-2015-v9") {
        return [
          moduleData.slug,
          {
            ...moduleData,
            subtitle:
              "Test BAC complet in format de foaie elev, reconstruit din pachetul ZIP 2015 V9 si randat ca Exercitiu BAC 2014, V4.",
            intro:
              "Lucrezi pe Subiectul I, Subiectul II si Subiectul III din aceeasi interfata cu navigare pe subiecte, raspunsuri salvate local si finalizare cu raport elev.",
            answerSheet: buildBac2015V9AnswerSheet(),
            teacherSolutionPayload: buildBac2015V9TeacherSolutionPayload(),
            teacherSolutionPdfFileName: "rezolvare_profesor_bac_2015_v9.pdf",
          },
        ]
      }

      if (moduleData.slug === "exercitiu-bac-2015-v2") {
        return [
          moduleData.slug,
          {
            ...moduleData,
            subtitle:
              "Test BAC complet in format de foaie elev, cu aceeasi asezare si logica de lucru ca Exercitiu BAC 2014, V4.",
            intro:
              "Lucrezi pe Subiectul I, Subiectul II si Subiectul III din aceeasi interfata cu navigare pe subiecte, raspunsuri salvate local si finalizare cu raport elev.",
            teacherSolutionSlug: "2015-v2",
            teacherSolutionPdfFileName: "rezolvare_profesor_bac_2015_v2.pdf",
            answerSheet: buildBac2015V2AnswerSheet(moduleData),
          },
        ]
      }

      const specialConfig = specialAnswerSheetsBySlug[moduleData.slug]
      const answerSheet = specialConfig?.answerSheet

      if (answerSheet) {
        return [
          moduleData.slug,
          {
            ...moduleData,
            title: specialConfig.preserveModuleTitle ? moduleData.title : answerSheet.title,
            subtitle: specialConfig.subtitle ?? moduleData.subtitle,
            intro: specialConfig.intro ?? moduleData.intro,
            answerSheet,
          },
        ]
      }

      if (shouldUseGenericGeneratedAnswerSheet(moduleData)) {
        const generatedAnswerSheet = buildGeneratedAnswerSheet(moduleData)

        return [
          moduleData.slug,
          {
            ...moduleData,
            subtitle:
              "Test BAC complet in format de foaie elev, cu aceeasi asezare si logica de lucru ca Exercitiu BAC 2014, V4.",
            intro:
              "Lucrezi pe Subiectul I, Subiectul II si Subiectul III din aceeasi interfata cu navigare pe subiecte, raspunsuri salvate local si finalizare cu raport elev.",
            answerSheet: generatedAnswerSheet,
            teacherSolutionPayload: buildGeneratedTeacherSolutionPayload(moduleData),
            teacherSolutionPdfFileName: `rezolvare_profesor_bac_${getGeneratedVariantToken(moduleData)}.pdf`,
          },
        ]
      }

      return [moduleData.slug, moduleData]
    }),
  )
}

async function loadTrackModules(trackSlug) {
  if (trackModuleCache[trackSlug]) {
    return trackModuleCache[trackSlug]
  }

  if (!trackPromiseCache[trackSlug]) {
    const loader = trackLoaders[trackSlug]

    if (!loader) {
      return null
    }

    trackPromiseCache[trackSlug] = loader().then((modulePayload) => {
      const payload = modulePayload.default ?? modulePayload
      const moduleMap = buildModuleMap(payload)
      trackModuleCache[trackSlug] = moduleMap
      return moduleMap
    })
  }

  return trackPromiseCache[trackSlug]
}

export async function loadGeneratedExerciseModule(trackSlug, moduleSlug) {
  const modulesBySlug = await loadTrackModules(trackSlug)
  return modulesBySlug?.[moduleSlug] ?? null
}
