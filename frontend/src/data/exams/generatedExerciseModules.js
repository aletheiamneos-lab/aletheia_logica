function getZipTeacherAnswer(config, item) {
  const teacher = config.teacherSolution ?? {}
  const itemId = String(item?.id ?? "")
  const normalizedItemId = getZipItemId(item)
  const groupId = getPartGroupId(itemId)
  const sMatch = itemId.match(/^S([123])_([^_]+)(?:_(\d+))?$/i)
  const sSubjectKey = sMatch ? `S${sMatch[1]}` : ""
  const sPartKey = sMatch?.[2]?.toUpperCase()
  const sNumberKey = sMatch?.[3] ?? (/^\d+$/.test(sPartKey ?? "") ? sPartKey : undefined)
  const candidateKeys = [
    itemId,
    normalizedItemId,
    groupId,
    itemId.replace(/_/g, "."),
    normalizedItemId.replace(/_/g, "."),
    groupId.replace("_", "."),
    sPartKey,
    sNumberKey,
  ].filter(Boolean)
  const containers = [
    teacher.answers,
    teacher.answerKey,
    teacher.solutions,
    teacher.answers?.subject_II,
    teacher.answers?.subject_III,
    sSubjectKey ? teacher.answers?.[sSubjectKey] : null,
    sSubjectKey ? teacher.answerKey?.[sSubjectKey] : null,
    sSubjectKey ? teacher.solutions?.[sSubjectKey] : null,
  ]

  for (const container of containers) {
    if (!container || typeof container !== "object") continue
    for (const key of candidateKeys) {
      if (container[key] !== undefined) return container[key]
    }
  }

  return undefined
}

