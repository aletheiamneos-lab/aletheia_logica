function convertPartBasedDiagramSpec(config, diagram) {
  const type = String(diagram.type ?? diagram.diagramType ?? "").toLowerCase()

  if (type.includes("venn")) {
    const schemaMap = getPartSyllogismSchemaMap(config)
    const directMode =
      diagram.mode ??
      diagram.mood ??
      diagram.teacherModel?.mode ??
      diagram.teacherModel?.mood ??
      diagram.teacherRendering?.mode ??
      diagram.teacherRendering?.mood ??
      inferModeFromDiagramId(diagram.diagramId)
    if (directMode) {
      addPartSyllogismSchema(schemaMap, directMode, diagram, diagram.validity ?? diagram.teacherModel?.validity)
      if (diagram.teacherModel) {
        addPartSyllogismSchema(schemaMap, directMode, diagram.teacherModel, diagram.teacherModel.validity ?? diagram.validity)
      }
      if (diagram.teacherRendering) {
        addPartSyllogismSchema(schemaMap, directMode, diagram.teacherRendering, diagram.teacherRendering.validity ?? diagram.validity)
      }
    }
    const modes = getPartDiagramModeEntries(diagram, schemaMap)

    if (modes.length) {
      const firstMode = modes[0]
      const spec = buildVennSpecFromMode(diagram.diagramId, firstMode.mode, firstMode.validity, schemaMap)
      spec.extraModes = modes.slice(1).map((entry) => ({
        mode: entry.mode,
        validity: normalizePartValidity(entry.validity),
        schemaText: schemaMap[String(entry.mode ?? "").toLowerCase()]?.schemaText,
      }))
      spec.renderHints.caption = diagram.expectedModes || modes.length > 1
        ? modes
        .map((entry) => {
          const mode = String(entry.mode ?? "").toLowerCase()
          return `${mode}: ${schemaMap[mode]?.schemaText ?? "schema in barem"} - ${
            normalizePartValidity(entry.validity) || "verificare"
          }`
        })
        .join(" | ")
        : spec.renderHints.caption
      return spec
    }

    return buildVennSpecFromMode(diagram.diagramId, diagram.mode, diagram.validity, schemaMap)
  }

  const natural = formatPartDiagramRelations(diagram)

  return {
    diagramId: diagram.diagramId,
    type: "euler_relation_map",
    natural,
    studentAction: natural ?? "Reprezinta raporturile dintre termeni.",
    renderHints: {
      style: "euler_relation_map",
      caption: natural ?? "Diagrama Euler",
    },
  }
}

