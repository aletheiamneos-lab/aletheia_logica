function mergePartSolution(solution, override) {
  if (!override || !Object.keys(override).length) {
    return solution
  }

  if (!solution || typeof solution !== "object" || Array.isArray(solution)) {
    return override
  }

  return {
    ...solution,
    ...override,
  }
}

function getNestedPartSolution(config, partId) {
  const teacher = config.teacherSolution ?? {}
  const groupId = getPartGroupId(partId)
  const normalizedId = normalizeZipPartKey(partId)
  const directSolution = Array.isArray(teacher.solutions)
    ? teacher.solutions.find((entry) => normalizeZipPartKey(entry.id ?? entry.sectionId ?? entry.groupId) === normalizedId)
    : null

  if (directSolution) {
    return directSolution
  }

  if (teacher.solutions && typeof teacher.solutions === "object" && !Array.isArray(teacher.solutions)) {
    const solutionKey = partId in teacher.solutions ? partId : groupId in teacher.solutions ? groupId : normalizedId
    if (teacher.solutions[solutionKey]) {
      return teacher.solutions[solutionKey]
    }
  }

  if (teacher.answers) {
    const answerKey = partId in teacher.answers ? partId : groupId in teacher.answers ? groupId : normalizedId
    if (teacher.answers[answerKey]) {
      return teacher.answers[answerKey]
    }
  }

  if (teacher.items) {
    if (teacher.items[partId]) return teacher.items[partId]
    if (teacher.items[groupId]) return teacher.items[groupId]
    if (teacher.items[normalizedId]) return teacher.items[normalizedId]
  }

  if (teacher.answerKey) {
    const answerKey =
      partId in teacher.answerKey
        ? partId
        : groupId in teacher.answerKey
          ? groupId
          : groupId.replace("_", ".") in teacher.answerKey
            ? groupId.replace("_", ".")
            : normalizedId
    if (teacher.answerKey[answerKey]) {
      return teacher.answerKey[answerKey]
    }
  }

  const teacherSection = getTeacherSectionEntry(teacher, partId)
  if (teacherSection) {
    return teacherSection
  }

  if (teacher.sections) {
    if (teacher.sections[partId]) return teacher.sections[partId]
    if (teacher.sections[groupId]) return teacher.sections[groupId]
    if (groupId.startsWith("II_")) return teacher.sections.II?.[groupId.replace("II_", "")]
    if (groupId.startsWith("III_")) return teacher.sections.III?.[groupId.replace("III_", "")]
  }

  if (groupId.startsWith("I_")) {
    return teacher.subiectul_I?.[groupId.replace("I_", "")]
  }
  if (groupId.startsWith("II_")) {
    return teacher.subiectul_II?.[groupId.replace("II_", "")]
  }
  if (groupId === "III_A") {
    return teacher.subiectul_III?.A
  }
  if (groupId.startsWith("III_")) {
    return teacher.subiectul_III?.[groupId.replace("III_", "")]
  }

  return null
}

function getPartSolution(config, partId) {
  const solution = getNestedPartSolution(config, partId)
  const override = getPartOverride(config, "solutionOverrides", partId) ?? {}

  return mergePartSolution(solution, override)
}

