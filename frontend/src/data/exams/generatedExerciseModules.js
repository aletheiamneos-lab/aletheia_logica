function inferZipDiagramFormula(diagram) {
  const prompt = stripZipDiacritics(diagram?.prompt).toLowerCase()

  if (prompt.startsWith("niciun") || diagram?.expected_structure?.relation === "disjoint") {
    return "SeP"
  }

  if (prompt.startsWith("toti")) {
    return "SaP"
  }

  if (prompt.startsWith("unele") && prompt.includes(" nu ")) {
    return "SoP"
  }

  if (prompt.startsWith("unele")) {
    return "SiP"
  }

  return diagram?.schema ?? "categorical"
}

function convertZipDiagramSpec(diagram) {
  const type = String(diagram?.type ?? "").toLowerCase()
  if (type.includes("venn")) {
    const task = diagram.tasks?.[0]
    const mode = diagram.mode ?? diagram.moodFigure ?? task?.mode
    const schema = diagram.schema ?? diagram.expectedSchema ?? task?.scheme
    const validity = diagram.expected_validity ?? diagram.teacherOnlyDecision ?? diagram.expectedValidity ?? task?.expectedValidity
    const schemaParts = parseZipSchemaParts(schema)

    return {
      diagramId: diagram.diagramId,
      type: "venn_three_terms",
      mode,
      validity,
      labels: { S: "S", P: "P", M: "M" },
      schemaText: schemaParts.join(" / "),
      vennActions: schemaParts.slice(0, 2).map((premise, index) => ({
        step: index + 1,
        premise,
        action: "mark",
        meaning: `Premisa ${index + 1}: ${premise}`,
      })),
      renderHints: {
        style: "venn3_small",
        caption: [mode, schemaParts.join(" / "), validity].filter(Boolean).join(": "),
      },
      ...(diagram.tasks?.length > 1
        ? {
            extraModes: diagram.tasks.slice(1).map((entry) => ({
              mode: entry.mode,
              validity: entry.expectedValidity,
              schemaText: parseZipSchemaParts(entry.scheme).join(" / "),
            })),
          }
        : {}),
    }
  }

  const natural = diagram.prompt ?? diagram.statement ?? diagram.proposition ?? diagram.instruction
  const relation = diagram.expected_structure?.relation ?? diagram.expectedRelation

  return {
    diagramId: diagram.diagramId,
    type: "euler_categorical",
    formula: inferZipDiagramFormula(diagram),
    natural,
    relation,
    studentAction: diagram.teacher_hint ?? diagram.studentAction,
    renderHints: {
      style: "euler2_small",
      caption: natural,
      note: `${(diagram.expected_structure?.sets ?? []).join(" / ")} - ${relation ?? ""}`,
    },
  }
}

