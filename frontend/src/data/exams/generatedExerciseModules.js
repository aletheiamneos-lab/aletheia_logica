function normalizeTeacherSectionId(value) {
  return stripZipDiacritics(value).replace(/[^A-Za-z0-9]+/g, "").toUpperCase()
}

function inferTeacherEntryGroupId(entry) {
  const direct = entry?.section ?? entry?.sectionId ?? entry?.groupId ?? entry?.id
  if (direct) {
    return getPartGroupId(String(direct).replace(/\./g, "_"))
  }

  const itemId = String(entry?.itemId ?? "")
  const match = itemId.match(/^(I|II|III)_([A-Z])/i)
  return match ? `${match[1].toUpperCase()}_${match[2].toUpperCase()}` : ""
}

function getTeacherSectionAliases(partId) {
  const groupId = getPartGroupId(partId)
  const normalizedGroup = normalizeTeacherSectionId(groupId)
  const aliases = new Set([
    normalizeTeacherSectionId(partId),
    normalizedGroup,
    normalizeTeacherSectionId(groupId.replace("_", ".")),
  ])

  if (normalizedGroup === "IA") aliases.add("S1A")
  if (normalizedGroup === "IB") aliases.add("S1B")
  if (normalizedGroup.startsWith("II")) aliases.add(`S2${normalizedGroup.slice(2)}`)
  if (normalizedGroup.startsWith("III")) aliases.add(`S3${normalizedGroup.slice(3)}`)

  return aliases
}

function teacherEntryMatchesPart(entry, partId) {
  const aliases = getTeacherSectionAliases(partId)
  const candidate = inferTeacherEntryGroupId(entry)
  return aliases.has(normalizeTeacherSectionId(candidate)) || aliases.has(normalizeTeacherSectionId(entry?.itemId))
}

function appendTeacherSectionCandidate(entries, entry, partId) {
  if (!entry || typeof entry !== "object") return
  if (teacherEntryMatchesPart(entry, partId)) {
    entries.push(entry)
  }

  ;["groups", "solutions", "items", "answers"].forEach((collectionName) => {
    const collection = entry[collectionName]
    if (Array.isArray(collection)) {
      collection.forEach((child) => appendTeacherSectionCandidate(entries, child, partId))
    } else if (collection && typeof collection === "object") {
      Object.entries(collection).forEach(([key, child]) => {
        if (getTeacherSectionAliases(partId).has(normalizeTeacherSectionId(key))) {
          entries.push(child)
        }
        appendTeacherSectionCandidate(entries, child, partId)
      })
    }
  })
}

function getTeacherSectionEntries(teacher, partId) {
  const entries = []
  const normalizedIds = getTeacherSectionAliases(partId)

  ;["answerKey", "answers", "items"].forEach((containerName) => {
    const container = teacher?.[containerName]
    if (!container) {
      return
    }

    if (Array.isArray(container)) {
      const matchingItems = container.filter((entry) => teacherEntryMatchesPart(entry, partId))
      if (matchingItems.length) {
        entries.push(matchingItems)
      }
      return
    }

    if (typeof container === "object") {
      Object.entries(container).forEach(([key, entry]) => {
        if (normalizedIds.has(normalizeTeacherSectionId(key))) {
          entries.push(entry)
        }
        appendTeacherSectionCandidate(entries, entry, partId)
      })
    }
  })

  const sections = teacher?.sections
  if (Array.isArray(sections)) {
    sections.forEach((section) => {
      if (!section || typeof section !== "object") return
      if (normalizedIds.has(normalizeTeacherSectionId(section.id))) {
        entries.push(section)
      }
      appendTeacherSectionCandidate(entries, section, partId)

      const solutions = section.solutions
      if (Array.isArray(solutions)) {
        solutions.forEach((entry) => appendTeacherSectionCandidate(entries, entry, partId))
      } else if (solutions && typeof solutions === "object") {
        Object.entries(solutions).forEach(([key, entry]) => {
          if (normalizedIds.has(normalizeTeacherSectionId(key))) {
            entries.push(entry)
          }
        })
      }
    })
  } else if (sections && typeof sections === "object") {
    Object.entries(sections).forEach(([key, entry]) => {
      if (normalizedIds.has(normalizeTeacherSectionId(key))) {
        entries.push(entry)
      }
    })
  }

  if (Array.isArray(teacher?.solutions)) {
    teacher.solutions.forEach((entry) => appendTeacherSectionCandidate(entries, entry, partId))
  } else if (teacher?.solutions && typeof teacher.solutions === "object") {
    Object.entries(teacher.solutions).forEach(([key, entry]) => {
      if (normalizedIds.has(normalizeTeacherSectionId(key))) {
        entries.push(entry)
      }
      appendTeacherSectionCandidate(entries, entry, partId)
    })
  }

  return entries.filter(Boolean)
}

