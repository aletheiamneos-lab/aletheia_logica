function getZipItemId(item) {
  const raw = String(item?.id ?? item?.itemId ?? item?.key ?? "")
  const dottedMatch = raw.match(/^(I|II|III)\.([A-Za-z0-9]+)(?:\.(\d+))?$/i)
  if (dottedMatch) {
    const subject = dottedMatch[1].toUpperCase()
    const part = dottedMatch[2].toUpperCase()
    if (subject === "I" && /^\d+$/.test(part)) return `I_A_${part}`
    if (subject === "III" && /^\d+$/.test(part)) return `III_${part}`
    return `${subject}_${part}`
  }

  const sMatch = raw.match(/^S([123])_([A-Za-z])(?:_(\d+))?$/i)
  if (sMatch) {
    const subject = sMatch[1] === "1" ? "I" : sMatch[1] === "2" ? "II" : "III"
    return `${subject}_${sMatch[2].toUpperCase()}${sMatch[3] ? `_${sMatch[3]}` : ""}`
  }

  const sNumericMatch = raw.match(/^S([123])_(\d+)$/i)
  if (sNumericMatch) {
    const subject = sNumericMatch[1] === "1" ? "I" : sNumericMatch[1] === "2" ? "II" : "III"
    return `${subject}_${sNumericMatch[2]}`
  }

  return raw
    .replace(/\./g, "_")
    .replace(/[^A-Za-z0-9_]+/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "")
}

