function parsePoints(value, fallback = 0) {
  const match = String(value ?? "").match(/\d+/)
  return match ? Number.parseInt(match[0], 10) : fallback
}

function normalizeReference(value) {
  return String(value ?? "")
    .replace(/\./g, "_")
    .replace(/[^A-Za-z0-9_]+/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "")
    .toUpperCase()
}

function cleanGeneratedTitle(value, fallback) {
  const text = String(value ?? "")
    .replace(/^Subiectul\s+[IVX]+\.?/i, "")
    .replace(/^[-.\s]+/, "")
    .replace(/\s+/g, " ")
    .trim()

  return text || fallback
}

function getGeneratedVariantToken(moduleData) {
  return String(moduleData?.slug ?? moduleData?.id ?? "bac_generated")
    .replace(/^exercitiu-bac-/, "")
    .replace(/^bac-exercise-/, "")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "")
    .toLowerCase()
}

function getGeneratedExamId(moduleData) {
  return `bac_logica_${getGeneratedVariantToken(moduleData)}`
}

function getGeneratedDiagramId(moduleData, card, suffix) {
  const variantToken = getGeneratedVariantToken(moduleData)
  const referenceToken = normalizeReference(card?.reference ?? card?.title).toLowerCase()
  return `bac_${variantToken}_${referenceToken}_${suffix}`
}

function getGeneratedSourceFiles(moduleData) {
  return {
    subjectPdf: moduleData?.officialPaper?.subjectDownload?.fileName ?? "subiect.pdf",
    baremPdf: moduleData?.officialPaper?.baremDownload?.fileName ?? "barem.pdf",
  }
}

function getGeneratedSubjectId(reference) {
  const text = String(reference ?? "").trim().toUpperCase()
  if (text.startsWith("III")) {
    return "III"
  }

  if (text.startsWith("II")) {
    return "II"
  }

  return "I"
}

function getGeneratedSubjectTitle(subjectId) {
  if (subjectId === "III") {
    return "SUBIECTUL al III-lea"
  }

  if (subjectId === "II") {
    return "SUBIECTUL al II-lea"
  }

  return "SUBIECTUL I"
}

