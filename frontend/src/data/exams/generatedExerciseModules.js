function getPartTruthStatements(config, part) {
  const override = getPartOverride(config, "truthStatementOverrides", part.id)
  const groupId = getPartGroupId(part.id)
  const truthItem = (part.items ?? []).find((item) => isPartTruthContainer(item))
  const truthItemStatementOptions = getTruthStatementOptions(truthItem?.answerInput)
  const partStatementOptions = getTruthStatementOptions(part.answerInput)
  const rawStatements = (() => {
    if (override && Object.keys(override).length && !truthItem && !part.subitems && !part.statements && !part.answerInput?.statements) {
      return Object.entries(override).map(([label, statement]) => ({ label, statement }))
    }
    if (
      truthItem?.subitems ||
      truthItem?.items ||
      truthItem?.statements ||
      truthItem?.answerInput?.statements ||
      truthItem?.answerInput?.items ||
      truthItemStatementOptions
    ) {
      return (
        truthItem.subitems ??
        truthItem.items ??
        truthItem.statements ??
        truthItem.answerInput.statements ??
        truthItem.answerInput.items ??
        truthItemStatementOptions
      )
    }
    if (part.subitems || part.statements || part.answerInput?.statements || part.answerInput?.items || partStatementOptions) {
      return part.subitems ?? part.statements ?? part.answerInput.statements ?? part.answerInput.items ?? partStatementOptions
    }
    return (part.items ?? []).filter(
      (item) =>
        !getPartDiagramId(item) &&
        (isPartTruthItem(item) || item?.statement || item?.text || item?.title || item?.prompt || item?.officialPrompt),
    )
  })()
  const statementEntries =
    rawStatements && typeof rawStatements === "object" && !Array.isArray(rawStatements)
      ? Object.entries(rawStatements).map(([label, statement]) => ({ label, statement }))
      : rawStatements

  return statementEntries.map((entry, index) => {
    const fallbackLabel = groupId === "I_B" ? String.fromCharCode(97 + index) : String(index + 1)
    if (Array.isArray(entry)) {
      const label = String(entry[0] ?? fallbackLabel).toLowerCase()
      return {
        label,
        statement: override?.[label] ?? String(entry[1] ?? ""),
      }
    }

    if (typeof entry === "string") {
      const label = /^[a-f]$/i.test(entry.trim()) ? entry.trim().toLowerCase() : fallbackLabel
      return {
        label,
        statement: override?.[label] ?? entry,
      }
    }

    const rawLabel = entry?.label ?? entry?.fieldId ?? entry?.key ?? entry?.number ?? entry?.id
    const label = String(rawLabel ? String(rawLabel).split("_").pop() : fallbackLabel).toLowerCase()
    return {
      label,
      statement: override?.[label] ?? entry?.prompt ?? entry?.officialPrompt ?? entry?.question ?? entry?.text ?? entry?.statement ?? entry?.title ?? "",
      points: entry?.points,
    }
  })
}

