function getPartGroupId(partId) {
  const raw = String(partId ?? "")
  const key = normalizeZipPartKey(raw)
  const dotted = raw.replace(/[.-]/g, "_").toUpperCase()

  if (/^I_A(?:_\d+)?$/.test(dotted) || /^I_\d+$/.test(dotted)) return "I_A"
  if (/^I_B/.test(dotted)) return "I_B"
  if (/^II_[A-Z]/.test(dotted)) return dotted.match(/^II_([A-Z])/) ? `II_${dotted.match(/^II_([A-Z])/)?.[1]}` : dotted
  if (/^III_[A-Z]/.test(dotted)) return dotted.match(/^III_([A-Z])/) ? `III_${dotted.match(/^III_([A-Z])/)?.[1]}` : dotted
  if (/^III_\d+$/.test(dotted)) return dotted
  if (/^S2_\d+$/.test(dotted)) return `II_${dotted.match(/^S2_(\d+)$/)?.[1]}`
  if (/^S3_\d+$/.test(dotted)) return `III_${dotted.match(/^S3_(\d+)$/)?.[1]}`

  if (raw === "I_A" || key === "S1A") return "I_A"
  if (raw === "I_B" || key === "S1B") return "I_B"
  if (raw.startsWith("II_") || raw.startsWith("III_")) return raw

  const subject = key.startsWith("S1") ? "I" : key.startsWith("S2") ? "II" : key.startsWith("S3") ? "III" : key
  const letter = key.match(/^S\d([A-Z])$/)?.[1] ?? key.match(/^S\d([A-Z])/)?.[1] ?? "A"
  return `${subject}_${letter}`
}

