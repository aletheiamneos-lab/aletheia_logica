function getZipGroupTitle(item) {
  if (item?.title) {
    return item.title
  }

  const groupId = getPartGroupId(item?.id)
  const suffix = groupId.split("_")[1]
  if (groupId === "I_B") {
    return "B. Scheme silogistice si diagrame Venn"
  }
  if (/^\d+$/.test(suffix)) {
    return `${suffix}.`
  }
  if (/^[A-Z]$/.test(suffix)) {
    return `${suffix}.`
  }
  return groupId.replace("_", ".")
}

function extractZipPropositions(intro) {
  const text = String(intro ?? "").trim()
  const afterColon = text.includes(":") ? text.slice(text.indexOf(":") + 1).trim() : text
  const propositions = [...afterColon.matchAll(/(?:^|\s)(\d+\.\s*.*?)(?=\s+\d+\.|$)/g)].map((match) =>
    match[1].trim(),
  )

  return propositions.length ? propositions : afterColon ? [afterColon] : []
}

function getZipSectionContextItems(section) {
  if (Array.isArray(section.givenPropositions) && section.givenPropositions.length) {
    return section.givenPropositions.map((item, index) => {
      const text = String(item ?? "").trim()
      return /^\d+\./.test(text) ? text : `${index + 1}. ${text}`
    })
  }

  const statementList = getZipSectionItems(section).find((item) => item.type === "statement_list")
  if (Array.isArray(statementList?.statements) && statementList.statements.length) {
    return statementList.statements
  }

  return extractZipPropositions(section.intro)
}

function buildZipDerivedGroups(config, section, subjectId) {
  if (subjectId === "I") {
    const choiceItems = getZipChoiceItems(section)
    const groups = []

    if (choiceItems.length) {
      groups.push(
        {
          id: "I_A",
          title: "A. Itemi cu alegere unica",
          points: getZipChoiceGroupPoints(section),
          officialPrompt: getZipChoiceGroupInstruction(section),
          answerType: "single_choice_group",
          items: choiceItems.map((item, index) =>
            convertZipStudentItem(config, normalizeZipChoiceItem(section, item, index)),
          ),
        },
      )
    }

    getZipNonChoiceItems(section).forEach((item) => {
      groups.push({
        id: getPartGroupId(item.id),
        title: getZipGroupTitle(item),
        points: getZipItemPoints(config, item),
        officialPrompt: getZipItemPrompt(item),
        items: [convertZipStudentItem(config, item)],
      })
    })

    return groups
  }

  return getZipSectionItems(section)
    .filter((item) => item.type !== "statement_list")
    .map((item) => ({
      id: getPartGroupId(item.id),
      title: getZipGroupTitle(item),
      points: getZipItemPoints(config, item),
      officialPrompt: getZipItemPrompt(item),
      items: [convertZipStudentItem(config, item)],
    }))
}

