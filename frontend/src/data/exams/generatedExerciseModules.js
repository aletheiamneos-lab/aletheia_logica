function distributeZipPoints(total, count) {
  if (count <= 0) {
    return []
  }

  const numericTotal = Math.max(0, Number(total ?? 0))
  const base = Math.floor(numericTotal / count)
  let remainder = numericTotal - base * count

  return Array.from({ length: count }, () => {
    const extra = remainder > 0 ? 1 : 0
    remainder -= extra
    return base + extra
  })
}

