function parseSyllogismSchemasFromAnswer(answer) {
  return Object.fromEntries(
    [...String(answer ?? "").matchAll(/([aeio]{3}-\d)\s*:\s*([^.-]+?\/[^.-]+?\/[^.-]+?)\s*-\s*(valid|invalid|nevalid)/gi)]
      .map((match) => {
        const mode = match[1].toLowerCase()
        const schemaText = match[2].trim()
        const validity = normalizePartValidity(match[3])
        const [major, minor, conclusion] = parseZipSchemaParts(schemaText)

        return [
          mode,
          {
            mode,
            schemaText,
            validity,
            major,
            minor,
            conclusion,
          },
        ]
      }),
  )
}

function addPartSyllogismSchema(schemaMap, mode, source, fallbackValidity) {
  const normalizedMode = String(mode ?? "").toLowerCase()
  if (!normalizedMode) {
    return
  }

  const sourceObject = source?.teacherModel ?? source
  const schemaParts = Array.isArray(sourceObject)
    ? sourceObject
    : typeof sourceObject === "string"
      ? parseZipSchemaParts(sourceObject)
    : Array.isArray(sourceObject?.premises)
      ? [...sourceObject.premises, sourceObject.conclusion].filter(Boolean)
      : sourceObject?.scheme ?? sourceObject?.schema ?? parseZipSchemaParts(sourceObject?.schemaText ?? sourceObject?.answer)
  const [major, minor, conclusion] = parseZipSchemaParts(Array.isArray(schemaParts) ? schemaParts.join("/") : schemaParts)
  const validity = normalizePartValidity(sourceObject?.decision ?? sourceObject?.validity ?? fallbackValidity)
  const hasSchemaParts = Boolean(major || minor || conclusion)
  const existing = schemaMap[normalizedMode]

  if (!hasSchemaParts && existing) {
    schemaMap[normalizedMode] = {
      ...existing,
      validity: validity || existing.validity,
    }
    return
  }

  schemaMap[normalizedMode] = {
    mode: normalizedMode,
    schemaText: [major, minor, conclusion].filter(Boolean).join(" / "),
    validity,
    major,
    minor,
    conclusion,
  }
}

function addPartSyllogismSchemasFromObject(schemaMap, source) {
  if (Array.isArray(source)) {
    source.forEach((entry) => addPartSyllogismSchemasFromObject(schemaMap, entry))
    return
  }

  if (!source || typeof source !== "object") {
    return
  }

  if (source.correctAnswer && typeof source.correctAnswer === "object") {
    addPartSyllogismSchemasFromObject(schemaMap, source.correctAnswer)
  }

  if (source.correctAnswers && typeof source.correctAnswers === "object") {
    addPartSyllogismSchemasFromObject(schemaMap, source.correctAnswers)
  }

  if (source.answers && typeof source.answers === "object") {
    addPartSyllogismSchemasFromObject(schemaMap, source.answers)
  }

  if (source.teacherModel && typeof source.teacherModel === "object") {
    const mode = source.mode ?? source.mood
    if (mode) {
      addPartSyllogismSchema(schemaMap, mode, source.teacherModel, source.teacherModel.validity ?? source.validity)
    }
    addPartSyllogismSchemasFromObject(schemaMap, source.teacherModel)
  }

  if (source.teacherRendering && typeof source.teacherRendering === "object") {
    const mode = source.mode ?? source.mood ?? source.teacherRendering.mode ?? source.teacherRendering.mood
    if (mode) {
      addPartSyllogismSchema(schemaMap, mode, source.teacherRendering, source.teacherRendering.validity ?? source.validity)
    }
    addPartSyllogismSchemasFromObject(schemaMap, source.teacherRendering)
  }

  if ((source.mode || source.mood) && (source.scheme || source.schema || source.premises)) {
    addPartSyllogismSchema(schemaMap, source.mode ?? source.mood, source, source.validity)
  }

  if (source.modes && typeof source.modes === "object" && !Array.isArray(source.modes)) {
    Object.entries(source.modes).forEach(([mode, entry]) => addPartSyllogismSchema(schemaMap, mode, entry, entry?.validity))
  }

  if (Array.isArray(source.modes) && source.premises && typeof source.premises === "object") {
    source.modes.forEach((mode) => {
      const premises = source.premises?.[mode] ?? source.premises?.[String(mode).toLowerCase()]
      const conclusion =
        source.conclusions?.[mode] ??
        (source.conclusion && typeof source.conclusion === "object" ? source.conclusion?.[mode] : source.conclusion)
      addPartSyllogismSchema(schemaMap, mode, [...(premises ?? []), conclusion].filter(Boolean), source.validity?.[mode])
    })
  }

  if (source.schemes && typeof source.schemes === "object") {
    Object.entries(source.schemes).forEach(([mode, entry]) =>
      addPartSyllogismSchema(schemaMap, mode, entry, source.validity?.[mode]),
    )
  }

  if (source.schemas && typeof source.schemas === "object") {
    Object.entries(source.schemas).forEach(([mode, entry]) =>
      addPartSyllogismSchema(schemaMap, mode, entry, source.validity?.[mode]),
    )
  }

  Object.entries(source).forEach(([key, entry]) => {
    if (/^[aeio]{3}-\d$/i.test(key)) {
      addPartSyllogismSchema(schemaMap, key, entry, source.validity?.[key])
    }
  })
}

