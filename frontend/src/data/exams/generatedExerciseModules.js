function generatedCardToTeacherItem(card, moduleData) {
  const itemId = normalizeReference(card.reference ?? card.title)
  const points = parsePoints(card.marks, parsePoints(card.points, 0))
  const officialPrompt = card.officialText ?? card.prompt ?? card.title ?? ""
  const item = {
    itemId,
    points,
    officialPrompt,
  }

  if (card.correctAnswer) {
    item.correctLetter = card.correctAnswer
    item.answer = card.correctAnswerLabel ?? `${card.correctAnswer})`
  } else if (Array.isArray(card.correctAnswers) && card.correctAnswers.length) {
    item.answers = card.correctAnswers
  } else if (card.answer) {
    item.answer = card.answer
  } else if (card.markingNote) {
    item.answer = card.markingNote
  } else {
    item.answer = "Raspuns evaluat manual conform baremului oficial."
  }

  if (card.correctExplanation || card.justification) {
    item.explanation = card.correctExplanation ?? card.justification
  }

  if (card.schema?.length) {
    item.schema = card.schema
  }

  if (card.steps?.length) {
    item.steps = card.steps
  }

  if (card.markingNote) {
    item.note = card.markingNote
  } else if (card.commonTrap) {
    item.note = card.commonTrap
  }

  if (itemId === "II_D") {
    item.diagramRef = getGeneratedDiagramId(moduleData, card, "euler")
  }

  if (itemId === "III_A") {
    item.diagramRef = getGeneratedDiagramId(moduleData, card, "venn")
  }

  return item
}

