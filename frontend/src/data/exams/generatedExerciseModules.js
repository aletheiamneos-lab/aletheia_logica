function isPartTruthContainer(item) {
  const id = String(item?.id ?? "").toLowerCase()
  return (
    isPartTruthItem(item) ||
    id.endsWith("_af") ||
    id.includes("true_false") ||
    Array.isArray(item?.statements) ||
    Array.isArray(item?.answerInput?.statements) ||
    Boolean(item?.statements && typeof item.statements === "object") ||
    Boolean(item?.answerInput?.statements && typeof item.answerInput.statements === "object") ||
    Array.isArray(item?.subitems) ||
    (Array.isArray(item?.items) &&
      item.items.some(
        (child) =>
          isPartTruthItem(child) ||
          Boolean(child?.statement) ||
          String(child?.id ?? "").toLowerCase().includes("true_false"),
      ))
  )
}

function getTruthStatementOptions(answerInput) {
  const options = answerInput?.options
  if (!Array.isArray(options) || !options.length) {
    return null
  }

  const looksLikeAnswerButtons =
    options.length <= 2 &&
    options.every((option) => {
      const value = typeof option === "string" ? option : (option.value ?? option.key ?? option.label)
      return ["A", "F", "ADEVARAT", "ADEVĂRAT", "FALS"].includes(stripZipDiacritics(value).toUpperCase())
    })

  return looksLikeAnswerButtons ? null : options
}

