function buildPartTeacherQuestionGroup(config, part) {
  if (shouldBuildPartTruthQuestion(config, part)) {
    return buildPartTeacherTruthQuestionGroup(config, part)
  }

  const solution = getPartSolution(config, part.id)
  const diagramRefs = getPartDiagramRefs(part)
  const diagramPoints = distributeZipPoints(4, diagramRefs.length)
  const primaryPoints = diagramRefs.length ? Math.max(0, Number(part.points ?? 0) - 4) : part.points
  const answer = normalizePartTeacherAnswer(solution)

  return {
    groupId: getPartGroupId(part.id),
    title: getPartTitle(config, part),
    points: part.points,
    officialPrompt: getPartPrompt(config, part),
    items: [
      {
        itemId: getPartGroupId(part.id),
        points: primaryPoints,
        officialPrompt: getPartPrompt(config, part),
        ...answer,
      },
      ...diagramRefs.map((diagramRef, index) => ({
        itemId: `${getPartGroupId(part.id)}_DIAGRAM_${index + 1}`,
        points: diagramPoints[index],
        officialPrompt: `Verificare prin diagrama Venn: ${diagramRef.label}`,
        diagramRef: diagramRef.diagramId,
        answer: `Diagrama pentru ${diagramRef.label}.`,
      })),
    ],
  }
}

function buildPartBasedTeacherGroups(config, section, subjectId) {
  const parts = getPartBasedWorkParts(config, section)

  if (subjectId === "I") {
    return parts.map((part) => {
      if (isPartChoiceGroup(part)) {
        return buildPartTeacherChoiceGroup(config, part)
      }

      return buildPartTeacherEulerTruthGroup(config, part)
    })
  }

  return parts.map((part) => buildPartTeacherQuestionGroup(config, part))
}

